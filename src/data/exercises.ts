const order = (id: string, text: string, steps: string[], explanation: string): Exercise => ({ kind: 'order', id, text, steps, explanation })
const match = (id: string, text: string, pairs: [string, string][], extra: string[], explanation: string): Exercise => ({ kind: 'match', id, text, pairs, extra, explanation })
const error = (id: string, text: string, lines: string[], errors: number[], fix: string, explanation: string): Exercise => ({ kind: 'error', id, text, lines, errors, fix, explanation })
/** Блок: [название, слой (индекс в zones) или null — лишний, почему он здесь или чем плох] */
const arch = (id: string, text: string, zones: string[], blocks: [string, number | null, string][], explanation: string): Exercise => ({
  kind: 'arch',
  id,
  text,
  zones,
  blocks: blocks.map(([title, zone, note]) => ({ title, zone, note })),
  explanation,
})

